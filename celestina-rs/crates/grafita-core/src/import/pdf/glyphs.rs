//! What a font's codes mean when it does not carry a `ToUnicode` map.
//!
//! Most PDFs in the world are older than `ToUnicode`, and a great many still
//! omit it for the standard fonts. What those carry instead is an `/Encoding`
//! with a `/Differences` array: a list saying "code 12 draws the glyph named
//! `fi`". Without reading it, code 12 falls through as a raw byte — which is a
//! form feed, so "Specification" is shown as "Specication" and the loss is
//! silent. That is the one outcome this crate refuses everywhere else, so the
//! names are read here.
//!
//! The table below is the Adobe glyph list for Latin text. The accented
//! letters are not typed out: their names follow the rule "base letter plus
//! accent", so they are derived by asking Unicode whether that letter exists,
//! and a name with no precomposed character is left out rather than guessed
//! at. The punctuation, ligatures and marks have no such rule and are listed.

