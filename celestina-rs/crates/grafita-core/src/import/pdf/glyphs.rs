/// The character a glyph name draws, when this crate knows the name.
///
/// The `uniXXXX` and `uXXXX` forms are computed rather than listed: they name
/// a code point outright, which is the one case where a name needs no table.
#[must_use]
pub fn name_to_char(name: &str) -> Option<char> {
    if let Some(digits) = name.strip_prefix("uni") {
        if digits.len() >= 4 {
            if let Ok(point) = u32::from_str_radix(&digits[..4], 16) {
                return char::from_u32(point);
            }
        }
    }
    if let Some(digits) = name.strip_prefix('u') {
        if (4..=6).contains(&digits.len()) {
            if let Ok(point) = u32::from_str_radix(digits, 16) {
                return char::from_u32(point);
            }
        }
    }
    // A name may carry a variant suffix, as in `a.sc` or `one.oldstyle`; the
    // base name is what says which character it draws.
    let base = name.split('.').next().unwrap_or(name);
    NAMES
        .binary_search_by_key(&base, |(candidate, _)| *candidate)
        .ok()
        .map(|index| NAMES[index].1)
}

#[cfg(test)]
mod tests {
    use super::name_to_char;

    #[test]
    fn the_table_is_sorted_so_it_can_be_searched() {
        assert!(
            super::NAMES.windows(2).all(|pair| pair[0].0 < pair[1].0),
            "the generated table must stay sorted and hold no duplicate"
        );
    }

    #[test]
    fn the_names_a_real_document_uses_are_known() {
        // The ligature and the dash this crate used to lose silently.
        assert_eq!(name_to_char("fi"), Some('\u{FB01}'));
        assert_eq!(name_to_char("emdash"), Some('\u{2014}'));
        assert_eq!(name_to_char("quoteright"), Some('\u{2019}'));
        // Derived rather than typed, and still right. Written as code points
        // because that is what the assertion is about, and because a literal
        // accented letter here reads to the language guard as prose.
        assert_eq!(name_to_char("eacute"), Some('\u{E9}'));
        assert_eq!(name_to_char("ntilde"), Some('\u{F1}'));
        assert_eq!(name_to_char("Ccedilla"), Some('\u{C7}'));
        // Computed forms and variant suffixes.
        assert_eq!(name_to_char("uni00F1"), Some('\u{F1}'));
        assert_eq!(name_to_char("a.sc"), Some('a'));
        // A name nobody defined stays unknown rather than becoming a guess.
        assert_eq!(name_to_char("nosuchglyph"), None);
    }
}
