#!/usr/bin/env python3
"""Generate the style's token outputs from celestina-style/tokens.toml.

    gen-tokens.py [--check] [--tokens PATH] [--out-qml PATH] [--out-rs PATH]

Writes two committed files from the one data file (spec 2026-10-14 §5.7):

- celestina-style/CelestinaDesignTokens.qml, a `pragma Singleton` QtObject with
  the reference palette (`ref`), one object per scheme (`schemeDark`) with
  the list of its role names (`schemeDarkRoles`), and every scalar section
  flattened to `<section><Key>` properties (`radiusLg`, `typeBody`,
  `motionCurveStandard`). CelestinaTheme.qml binds its tokens to it.
- celestina-rs/crates/celestina-tokens/src/generated.rs, plain Rust with no
  dependencies: `Rgba`, `Scheme` with one constant per scheme and
  `Scheme::by_name`, and one module per section (`ref` becomes `ref_palette`,
  `type` becomes `type_scale`).

Value forms: a colour is "#rrggbb", "#aarrggbb" or { color, alpha }. QML
always receives an 8-bit literal (a table alpha is rounded half-up to a
byte); Rust receives the alpha as `byte / 255` for the hex forms and as the
decimal for a table. An integer is a QML `int`, a float a QML `real`; in Rust
both are `f32`, except a `motion` integer, which is a duration in ms (`u32`,
named `<KEY>_MS`), and a `type` weight (`u16`). An array is a cubic bezier's
four control points: QML gets the BezierSpline end point `1, 1` appended,
Rust a `[f32; 4]`.

Every key must carry a one-line `#` comment directly above it; the comment is
the token's definition and follows it into both outputs. The same input
always gives the same bytes.

--check generates into a temporary directory and exits 1, with a unified
diff per stale output, when a committed output differs from what the
generator writes. Standard library only.
"""

from __future__ import annotations

import argparse
import difflib
import math
import pathlib
import re
import sys
import tempfile
import tomllib

HERE = pathlib.Path(__file__).resolve().parent
STYLE = HERE.parent
SUITE = STYLE.parent
TOKENS = STYLE / "tokens.toml"
OUT_QML = STYLE / "CelestinaDesignTokens.qml"
OUT_RS = SUITE / "celestina-rs" / "crates" / "celestina-tokens" / "src" / "generated.rs"

HEAD = "Generated by celestina-style/scripts/gen-tokens.py from tokens.toml — do not edit"
HEX = re.compile(r"#(?:[0-9a-f]{6}|[0-9a-f]{8})")
KEY = re.compile(r"[a-z][A-Za-z0-9]*")
TABLE_LINE = re.compile(r"\[([A-Za-z0-9_.]+)\]")
KEY_LINE = re.compile(r"([A-Za-z_][A-Za-z0-9_]*)\s*=")
RUST_MODULES = {"ref": "ref_palette", "type": "type_scale"}


class TokenError(Exception):
    """tokens.toml breaks a rule the generator relies on."""


class Tokens:
    """The parsed tokens and their comments.

    `comments` maps (table path, key) to the key's one-line comment and
    (table path, None) to the comment lines above a table header.
    """

    def __init__(self, data: dict, comments: dict) -> None:
        self.data = data
        self.comments = comments

    def comment(self, path: tuple[str, ...], key: str | None) -> list[str]:
        return self.comments.get((path, key), [])


# ── Reading ─────────────────────────────────────────────────────────────────


def read_comments(text: str, source: pathlib.Path) -> dict:
    comments: dict[tuple[tuple[str, ...], str | None], list[str]] = {}
    table: tuple[str, ...] = ()
    block: list[str] = []
    for number, line in enumerate(text.splitlines(), start=1):
        stripped = line.strip()
        if stripped.startswith("#"):
            block.append(stripped[1:].strip())
            continue
        if not stripped:
            block = []
            continue
        header = TABLE_LINE.fullmatch(stripped)
        if header:
            table = tuple(header.group(1).split("."))
            comments[(table, None)] = block
        else:
            key = KEY_LINE.match(stripped)
            if not key:
                raise TokenError(
                    f"{source}:{number}: one `key = value` per line, a table "
                    "header or a comment"
                )
            if len(block) > 1:
                raise TokenError(
                    f"{source}:{number}: the comment of `{key.group(1)}` is one line"
                )
            comments[(table, key.group(1))] = block
        block = []
    return comments


def load(source: pathlib.Path) -> Tokens:
    text = source.read_text(encoding="utf-8")
    try:
        data = tomllib.loads(text)
    except tomllib.TOMLDecodeError as error:
        raise TokenError(f"{source}: {error}") from error
    tokens = Tokens(data, read_comments(text, source))
    validate(tokens, (), data, source)
    for required in ("ref", "scheme"):
        if not isinstance(data.get(required), dict) or not data[required]:
            raise TokenError(f"{source}: no [{required}] table")
    for name, scheme in data["scheme"].items():
        if list(scheme) != list(next(iter(data["scheme"].values()))):
            raise TokenError(f"{source}: [scheme.{name}] has another role list")
    names = ["ref"] + [camel(("scheme", name)) for name in data["scheme"]]
    names += [camel(("scheme", name, "roles")) for name in data["scheme"]]
    names += flat_names((), {k: v for k, v in data.items() if k not in ("ref", "scheme")})
    seen: set[str] = set()
    for name in names:
        if name in seen:
            raise TokenError(f"{source}: two tokens flatten to the QML name `{name}`")
        seen.add(name)
    return tokens


def flat_names(path: tuple[str, ...], table: dict) -> list[str]:
    names: list[str] = []
    for key, value in table.items():
        if isinstance(value, dict) and not is_colour_table(value):
            names += flat_names(path + (key,), value)
        else:
            names.append(camel(path + (key,)))
    return names


def is_colour_table(value: object) -> bool:
    return isinstance(value, dict) and set(value) == {"color", "alpha"}


def validate(tokens: Tokens, path: tuple[str, ...], table: dict, source) -> None:
    for key, value in table.items():
        if not KEY.fullmatch(key):
            raise TokenError(f"{source}: `{'.'.join(path + (key,))}` is not a camelCase key")
        if isinstance(value, dict) and not is_colour_table(value):
            if path == () and key == "scheme":
                for name, scheme in value.items():
                    validate(tokens, (key, name), scheme, source)
            else:
                validate(tokens, path + (key,), value, source)
            continue
        if path == ():
            raise TokenError(f"{source}: `{key}` sits outside a table")
        if not tokens.comment(path, key):
            raise TokenError(
                f"{source}: `{'.'.join(path + (key,))}` has no comment above it"
            )
        if path[0] in ("ref", "scheme") or isinstance(value, (str, dict)):
            rgba(value)
        elif isinstance(value, list):
            curve(value)
        elif isinstance(value, bool) or not isinstance(value, (int, float)):
            raise TokenError(
                f"{source}: `{'.'.join(path + (key,))}` is not a colour, number or curve"
            )


def rgba(value: object) -> tuple[int, int, int, float]:
    """A colour token as 8-bit channels and an alpha in 0..1."""
    if is_colour_table(value):
        hex_text, alpha = value["color"], value["alpha"]  # type: ignore[index]
        if not isinstance(hex_text, str) or len(hex_text) != 7 or not HEX.fullmatch(hex_text):
            raise TokenError(f"a table colour is #rrggbb: {value!r}")
        if isinstance(alpha, bool) or not isinstance(alpha, (int, float)) or not 0 <= alpha <= 1:
            raise TokenError(f"a table alpha is a number in 0..1: {value!r}")
        red, green, blue = (int(hex_text[i : i + 2], 16) for i in (1, 3, 5))
        return red, green, blue, float(alpha)
    if not isinstance(value, str) or not HEX.fullmatch(value):
        raise TokenError(f"a colour is #rrggbb, #aarrggbb or {{ color, alpha }}: {value!r}")
    if len(value) == 7:
        red, green, blue = (int(value[i : i + 2], 16) for i in (1, 3, 5))
        return red, green, blue, 1.0
    alpha_byte, red, green, blue = (int(value[i : i + 2], 16) for i in (1, 3, 5, 7))
    return red, green, blue, alpha_byte / 255


def byte(channel: float) -> int:
    """A 0..1 channel as a byte, rounded half-up."""
    return min(255, max(0, math.floor(channel * 255 + 0.5)))


def curve(value: object) -> list[float]:
    if (
        not isinstance(value, list)
        or len(value) != 4
        or any(isinstance(v, bool) or not isinstance(v, (int, float)) for v in value)
    ):
        raise TokenError(f"a curve is four bezier control points: {value!r}")
    return [float(v) for v in value]


# ── Spelling ────────────────────────────────────────────────────────────────


def camel(parts: tuple[str, ...] | list[str]) -> str:
    head, *rest = parts
    return head + "".join(part[0].upper() + part[1:] for part in rest)


def snake(name: str) -> str:
    name = re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", name)
    name = re.sub(r"(?<=[A-Za-z])([0-9]+)", r"_\1", name)
    return name.lower()


def number(value: int | float) -> str:
    return str(value) if isinstance(value, int) else repr(float(value))


def rust_float(value: int | float) -> str:
    return f"{value}.0" if isinstance(value, int) else repr(float(value))


def qml_colour(value: object) -> str:
    if isinstance(value, str):
        rgba(value)
        return f'"{value}"'
    red, green, blue, alpha = rgba(value)
    return f'"#{byte(alpha):02x}{red:02x}{green:02x}{blue:02x}"'


def rust_colour(value: object, indent: str) -> str:
    """`Rgba { … }` in rustfmt's layout; `indent` is the opening line's."""
    red, green, blue, alpha = rgba(value)
    if is_colour_table(value):
        alpha_text = repr(alpha)
    else:
        alpha_byte = int(value[1:3], 16) if len(value) == 9 else 255  # type: ignore[index]
        alpha_text = {255: "1.0", 0: "0.0"}.get(alpha_byte, f"{alpha_byte}.0 / 255.0")
    inner = indent + "    "
    return (
        "Rgba {\n"
        f"{inner}r: {red},\n{inner}g: {green},\n{inner}b: {blue},\n{inner}a: {alpha_text},\n"
        f"{indent}}}"
    )


def is_colour(value: object) -> bool:
    return isinstance(value, str) or is_colour_table(value)


# ── QML ─────────────────────────────────────────────────────────────────────


def qml_comment(lines: list[str], indent: str) -> list[str]:
    return [f"{indent}// {line}".rstrip() for line in lines]


def qml_scalar(name: str, value: object) -> str:
    if is_colour(value):
        return f"readonly property color {name}: {qml_colour(value)}"
    if isinstance(value, list):
        points = ", ".join(number(point) for point in value)
        return f"readonly property var {name}: [{points}, 1, 1]"
    kind = "int" if isinstance(value, int) else "real"
    return f"readonly property {kind} {name}: {number(value)}"


def qml_colour_block(
    tokens: Tokens, path: tuple[str, ...], table: dict, component: str, prop: str
) -> list[str]:
    lines = qml_comment(tokens.comment(path, None), "    ")
    lines.append(f"    component {component}: QtObject {{")
    for key, value in table.items():
        lines += qml_comment(tokens.comment(path, key), "        ")
        lines.append(f"        readonly property color {key}: {qml_colour(value)}")
    lines.append("    }")
    lines.append(f"    readonly property {component} {prop}: {component} {{}}")
    return lines


def qml_section(tokens: Tokens, path: tuple[str, ...], table: dict) -> list[str]:
    lines = [""] + qml_comment(tokens.comment(path, None), "    ")
    for key, value in table.items():
        if isinstance(value, dict) and not is_colour_table(value):
            lines += qml_section(tokens, path + (key,), value)
            continue
        lines += qml_comment(tokens.comment(path, key), "    ")
        lines.append("    " + qml_scalar(camel(path + (key,)), value))
    return lines


def render_qml(tokens: Tokens) -> str:
    data = tokens.data
    lines = [
        "pragma Singleton",
        "",
        "import QtQuick",
        "",
        f"// {HEAD}.",
        "// CelestinaTheme.qml binds every token to these properties; consumers read",
        "// CelestinaTheme, never this file.",
        "QtObject {",
    ]
    lines += qml_colour_block(tokens, ("ref",), data["ref"], "RefTokens", "ref")
    for name, scheme in data["scheme"].items():
        prop = camel(("scheme", name))
        lines.append("")
        lines += qml_colour_block(
            tokens, ("scheme", name), scheme, prop[0].upper() + prop[1:] + "Tokens", prop
        )
        lines.append(f"    // The {name} scheme's role names, in declaration order.")
        lines.append(f"    readonly property var {prop}Roles: [")
        names = [f'        "{role}"' for role in scheme]
        lines += [name + "," for name in names[:-1]] + names[-1:]
        lines.append("    ]")
    for section, table in data.items():
        if section not in ("ref", "scheme"):
            lines += qml_section(tokens, (section,), table)
    lines.append("}")
    return "\n".join(lines) + "\n"


# ── Rust ────────────────────────────────────────────────────────────────────


def rust_doc(lines: list[str], indent: str) -> list[str]:
    return [f"{indent}/// {line}".rstrip() for line in lines]


def rust_const(path: tuple[str, ...], key: str, value: object, indent: str) -> str:
    name = snake(key).upper()
    if is_colour(value):
        return f"{indent}pub const {name}: Rgba = {rust_colour(value, indent)};"
    if isinstance(value, list):
        points = ", ".join(rust_float(point) for point in value)
        return f"{indent}pub const {name}: [f32; 4] = [{points}];"
    if isinstance(value, int) and path[0] == "motion":
        return f"{indent}pub const {name}_MS: u32 = {value};"
    if isinstance(value, int) and path[0] == "type" and key.startswith("weight"):
        return f"{indent}pub const {name}: u16 = {value};"
    return f"{indent}pub const {name}: f32 = {rust_float(value)};"


def has_colour(table: dict) -> bool:
    return any(
        is_colour(value)
        or (isinstance(value, dict) and not is_colour_table(value) and has_colour(value))
        for value in table.values()
    )


def rust_module(
    tokens: Tokens, path: tuple[str, ...], table: dict, name: str, indent: str
) -> list[str]:
    inner = indent + "    "
    lines = rust_doc(tokens.comment(path, None), indent)
    lines.append(f"{indent}pub mod {name} {{")
    body: list[list[str]] = []
    if has_colour(table):
        body.append([f"{inner}use {'super::' * len(path)}Rgba;"])
    for key, value in table.items():
        if isinstance(value, dict) and not is_colour_table(value):
            body.append(rust_module(tokens, path + (key,), value, snake(key), inner))
            continue
        body.append(
            rust_doc(tokens.comment(path, key), inner) + [rust_const(path, key, value, inner)]
        )
    for index, item in enumerate(body):
        if index:
            lines.append("")
        lines += item
    lines.append(f"{indent}}}")
    return lines


def render_rust(tokens: Tokens) -> str:
    data = tokens.data
    schemes = data["scheme"]
    roles = list(next(iter(schemes.values())))
    first = next(iter(schemes))
    lines = [
        f"//! {HEAD}.",
        "//!",
        "//! The Celestina style tokens (spec 2026-10-14 §5.7): one `Scheme` constant",
        "//! per scheme and one module per section of `celestina-style/tokens.toml`.",
        "",
        "/// A colour: 8-bit sRGB channels and an alpha in `0.0..=1.0`.",
        "#[derive(Clone, Copy, Debug, PartialEq)]",
        "pub struct Rgba {",
        "    pub r: u8,",
        "    pub g: u8,",
        "    pub b: u8,",
        "    pub a: f32,",
        "}",
        "",
        "/// One colour per semantic role of `CelestinaTheme`'s `ColorScheme`.",
        "#[derive(Clone, Copy, Debug, PartialEq)]",
        "pub struct Scheme {",
    ]
    for role in roles:
        lines += rust_doc(tokens.comment(("scheme", first), role), "    ")
        lines.append(f"    pub {snake(role)}: Rgba,")
    lines.append("}")
    for name, scheme in schemes.items():
        lines.append("")
        lines += rust_doc(tokens.comment(("scheme", name), None), "")
        lines.append(f"pub const {snake(name).upper()}: Scheme = Scheme {{")
        for role, value in scheme.items():
            lines.append(f"    {snake(role)}: {rust_colour(value, '    ')},")
        lines.append("};")
    lines += [
        "",
        "impl Scheme {",
        "    /// The scheme called `name`, or `None` when no scheme has that name.",
        "    pub fn by_name(name: &str) -> Option<&'static Scheme> {",
        "        match name {",
    ]
    lines += [f'            "{name}" => Some(&{snake(name).upper()}),' for name in schemes]
    lines += [
        "            _ => None,",
        "        }",
        "    }",
        "}",
    ]
    for section, table in data.items():
        if section == "scheme":
            continue
        lines.append("")
        lines += rust_module(
            tokens, (section,), table, RUST_MODULES.get(section, snake(section)), ""
        )
    return "\n".join(lines) + "\n"


# ── Command ─────────────────────────────────────────────────────────────────


def stale(path: pathlib.Path, expected: str) -> list[str]:
    try:
        current = path.read_text(encoding="utf-8")
    except FileNotFoundError:
        return [f"{path}: missing; run celestina-style/scripts/gen-tokens.py\n"]
    if current == expected:
        return []
    diff = difflib.unified_diff(
        current.splitlines(keepends=True),
        expected.splitlines(keepends=True),
        fromfile=f"{path} (committed)",
        tofile=f"{path} (generated)",
    )
    return [f"{path}: stale; run celestina-style/scripts/gen-tokens.py\n", *diff]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--check", action="store_true",
                        help="compare the outputs with a fresh generation; write nothing")
    parser.add_argument("--tokens", type=pathlib.Path, default=TOKENS)
    parser.add_argument("--out-qml", type=pathlib.Path, default=OUT_QML)
    parser.add_argument("--out-rs", type=pathlib.Path, default=OUT_RS)
    arguments = parser.parse_args(argv)

    try:
        tokens = load(arguments.tokens)
        outputs = {
            arguments.out_qml: render_qml(tokens),
            arguments.out_rs: render_rust(tokens),
        }
    except (OSError, TokenError) as error:
        print(f"gen-tokens: ERROR: {error}", file=sys.stderr)
        return 2

    if not arguments.check:
        for path, text in outputs.items():
            path.write_text(text, encoding="utf-8")
            print(f"gen-tokens: wrote {path}")
        return 0

    report: list[str] = []
    with tempfile.TemporaryDirectory(prefix="gen-tokens-") as temporary:
        scratch = pathlib.Path(temporary)
        for index, (path, text) in enumerate(outputs.items()):
            fresh = scratch / f"{index}-{path.name}"
            fresh.write_text(text, encoding="utf-8")
            report += stale(path, fresh.read_text(encoding="utf-8"))
    if report:
        sys.stderr.writelines(report)
        print("gen-tokens: ERROR: a generated output differs from tokens.toml", file=sys.stderr)
        return 1
    print("gen-tokens: OK (both outputs match tokens.toml)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
